begin;

create table if not exists public.user_profiles (
  id bigint generated by default as identity primary key,
  name text,
  preferences jsonb not null default '{}'::jsonb
);

lock table public.user_profiles in access exclusive mode;

-- Support an existing manually created table with a UUID primary key.
do $$
begin
  if exists (select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'user_profiles'
      and column_name = 'id' and udt_name = 'uuid') then
    alter table public.user_profiles alter column id set default gen_random_uuid();
  end if;
end $$;

alter table public.user_profiles
  add column if not exists name text,
  add column if not exists preferences jsonb not null default '{}'::jsonb,
  add column if not exists singleton boolean not null default true;

-- Never discard or combine existing profiles automatically.
do $$
begin
  if (select count(*) from public.user_profiles) > 1 then
    raise exception 'Przerwano: tabela zawiera kilka profili. Nie usunieto zadnych danych. Pokaz ten komunikat agentowi.';
  end if;
  if exists (select 1 from public.user_profiles
    where singleton is distinct from true
      or (preferences is not null and jsonb_typeof(preferences) <> 'object')) then
    raise exception 'Przerwano: istniejacy profil ma niezgodny format. Nie zmieniono danych.';
  end if;
end $$;

update public.user_profiles set preferences = '{}'::jsonb where preferences is null;
alter table public.user_profiles alter column preferences set default '{}'::jsonb;
alter table public.user_profiles alter column preferences set not null;
alter table public.user_profiles alter column singleton set default true;
alter table public.user_profiles alter column singleton set not null;
create unique index if not exists user_profiles_singleton_unique on public.user_profiles(singleton);

-- Enforce one possible key, hence at most one owner profile.
do $$
begin
  if not exists (select 1 from pg_constraint
    where conrelid = 'public.user_profiles'::regclass and conname = 'user_profiles_single_owner') then
    alter table public.user_profiles add constraint user_profiles_single_owner check (singleton = true);
  end if;
end $$;

-- Atomic merge prevents two simultaneous saves from overwriting older facts.
create or replace function public.save_owner_profile(p_name text, p_preferences jsonb)
returns void language plpgsql security invoker set search_path = '' as $$
begin
  if p_preferences is null or jsonb_typeof(p_preferences) <> 'object' then
    raise exception 'preferences must be a JSON object';
  end if;
  insert into public.user_profiles (singleton, name, preferences)
  values (true, p_name, p_preferences)
  on conflict (singleton) do update
  set name = coalesce(excluded.name, user_profiles.name),
      preferences = user_profiles.preferences || excluded.preferences;
end $$;

alter table public.user_profiles enable row level security;
do $$
declare item record;
begin
  for item in select policyname from pg_policies
    where schemaname = 'public' and tablename = 'user_profiles'
  loop
    execute format('drop policy %I on public.user_profiles', item.policyname);
  end loop;
end $$;

revoke all on public.user_profiles from public, anon, authenticated;
grant usage on schema public to service_role;
grant select, insert, update, delete on public.user_profiles to service_role;
revoke all on function public.save_owner_profile(text, jsonb) from public, anon, authenticated;
grant execute on function public.save_owner_profile(text, jsonb) to service_role;

do $$
declare seq text;
begin
  seq := pg_get_serial_sequence('public.user_profiles', 'id');
  if seq is not null then
    execute format('revoke all on sequence %s from public, anon, authenticated', seq);
    execute format('grant usage, select on sequence %s to service_role', seq);
  end if;
end $$;

notify pgrst, 'reload schema';
commit;
